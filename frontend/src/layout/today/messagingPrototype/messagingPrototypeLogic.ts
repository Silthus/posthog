// PROTOTYPE, never merged: Silthus/personal#212. Throwaway state for the Messaging home variants.
import { MakeLogicType, actions, kea, path, reducers } from 'kea'
import { router, urlToAction } from 'kea-router'

export type MessagingPrototypeVariant = 'A' | 'B' | 'C'

export const MESSAGING_PROTOTYPE_VARIANTS: MessagingPrototypeVariant[] = ['A', 'B', 'C']

export const MESSAGING_HOME_URL = '/messaging-prototype'
export const WORKFLOWS_ROW_URL = '/workflows-prototype'

function parseVariant(value: unknown): MessagingPrototypeVariant | null {
    return MESSAGING_PROTOTYPE_VARIANTS.includes(value as MessagingPrototypeVariant)
        ? (value as MessagingPrototypeVariant)
        : null
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface messagingPrototypeLogicValues {
    variant: MessagingPrototypeVariant | null
}

export interface messagingPrototypeLogicActions {
    setVariant: (variant: MessagingPrototypeVariant | null) => {
        variant: MessagingPrototypeVariant | null
    }
}

export type messagingPrototypeLogicType = MakeLogicType<messagingPrototypeLogicValues, messagingPrototypeLogicActions>

export const messagingPrototypeLogic = kea<messagingPrototypeLogicType>([
    path(['layout', 'today', 'messagingPrototype', 'messagingPrototypeLogic']),
    actions({
        setVariant: (variant: MessagingPrototypeVariant | null) => ({ variant }),
    }),
    reducers({
        variant: [
            null as MessagingPrototypeVariant | null,
            {
                setVariant: (_, { variant }) => variant,
            },
        ],
    }),
    urlToAction(({ actions, values }) => ({
        '*': (_, searchParams) => {
            const variant = parseVariant(searchParams.variant)
            if (variant && variant !== values.variant) {
                actions.setVariant(variant)
            }
        },
    })),
])

/** The variant a URL's query names. The shell's reducers read it here, because they may not read another logic. */
export function messagingPrototypeVariantFromSearch(search: string): MessagingPrototypeVariant | null {
    return parseVariant(new URLSearchParams(search).get('variant'))
}

/** The variant in force, for links built at render time. Null outside the prototype stories. */
export function messagingPrototypeVariant(): MessagingPrototypeVariant | null {
    return messagingPrototypeLogic.findMounted()?.values.variant ?? null
}

/** Keeps `?variant=` on every prototype link, so a reload or a shared link opens the same variant. */
export function withVariant(url: string): string {
    const variant = messagingPrototypeVariant()
    if (!variant) {
        return url
    }
    const [base, query = ''] = url.split('?')
    const params = new URLSearchParams(query)
    params.set('variant', variant)
    return `${base}?${params.toString()}`
}

export function switchVariant(variant: MessagingPrototypeVariant): void {
    messagingPrototypeLogic.actions.setVariant(variant)
    const { pathname, searchParams, hashParams } = router.values.currentLocation
    router.actions.replace(pathname, { ...searchParams, variant }, hashParams)
}
