    sandboxEmailSenderProvisionError: string | null // integrationsLogic
    sandboxEmailSenderProvisionResult: SandboxEmailSenderProvisionResult | null // integrationsLogic
    sandboxEmailSenderProvisionResultLoading: boolean // integrationsLogic
    sandboxEmailSenderSetupError: string | null // integrationsLogic
    activeCount: number
