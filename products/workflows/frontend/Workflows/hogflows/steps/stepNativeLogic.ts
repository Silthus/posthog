export const stepNativeLogic = kea<stepNativeLogicType>([
    path((key) => ['products', 'workflows', 'frontend', 'Workflows', 'hogflows', 'steps', 'stepNativeLogic', key]),
    props({} as StepNativeLogicProps),
    key(({ workflowLogicProps, actionId }: StepNativeLogicProps) => `${workflowLogicProps.id || 'new'}-${actionId}`),
    connect(({ workflowLogicProps }: StepNativeLogicProps) => ({
        values: [
            workflowLogic(workflowLogicProps),
            ['workflow', 'edgesByActionId'],
            workflowNodesLogic,
            ['workflowNodes', 'workflowNodesLoading'],
        ],
        actions: [
            workflowLogic(workflowLogicProps),
            ['setWorkflowAction', 'setWorkflowActionEdges'],
            workflowNodesLogic,
            ['loadWorkflowNodesSuccess'],
        ],
    })),
    actions({
        setOperation: (operation: string) => ({ operation }),
        addOutcomePath: (outcome: string) => ({ outcome }),
        removeOutcomePath: (outcome: string) => ({ outcome }),
    }),
    selectors({
        action: [
            (s) => [s.workflow, (_, props) => props.actionId],
            (workflow: HogFlow, actionId: string): NativeAction | null => {
                const action = workflow.actions.find((candidate) => candidate.id === actionId)
                return action?.type === 'native' ? action : null
            },
        ],
        actionEdges: [
            (s) => [s.edgesByActionId, (_, props) => props.actionId],
            (edgesByActionId: Record<string, HogFlowEdge[]>, actionId: string): HogFlowEdge[] =>
                edgesByActionId[actionId] ?? [],
        ],
        node: [
            (s) => [s.workflowNodes, s.action],
            (workflowNodes: WorkflowNodeApi[] | null, action: NativeAction | null): WorkflowNodeApi | null =>
                workflowNodes?.find((node) => node.key === action?.config.node) ?? null,
        ],
        operation: [
            (s) => [s.node, s.action],
            (node: WorkflowNodeApi | null, action: NativeAction | null): WorkflowNodeOperationApi | null =>
                node?.operations.find((operation) => operation.key === action?.config.operation) ?? null,
        ],
        outcomeEdges: [
            (s) => [s.actionEdges, (_, props) => props.actionId],
            (actionEdges: HogFlowEdge[], actionId: string): HogFlowEdge[] =>
                actionEdges.filter((edge) => edge.from === actionId && edge.outcome !== undefined),
        ],
        outcomePaths: [
            (s) => [s.operation, s.outcomeEdges, s.edgesByActionId],
            (
                operation: WorkflowNodeOperationApi | null,
                outcomeEdges: HogFlowEdge[],
                edgesByActionId: Record<string, HogFlowEdge[]>
            ): OutcomePath[] =>
                (operation?.outcomes.slice(1) ?? []).map((outcome) => {
                    const label = getOutcomeLabel(outcome)
                    const edge = outcomeEdges.find((candidate) => candidate.outcome === outcome)
                    if (!edge) {
                        return { outcome, label, hasPath: false }
                    }
                    const pathHasSteps = !(edgesByActionId[edge.to] ?? []).some(
                        (other) => other.to === edge.to && other !== edge
                    )
                    return {
                        outcome,
                        label,
                        hasPath: true,
                        removeDisabledReason: pathHasSteps ? 'Clean up branching steps first' : undefined,
                    }
                }),
        ],
        operationOptions: [
            (s) => [s.node, s.outcomeEdges],
            (node: WorkflowNodeApi | null, outcomeEdges: HogFlowEdge[]): OperationOption[] =>
                (node?.operations ?? []).map((operation) => {
                    const missingOutcome = outcomeEdges.find((edge) => !operation.outcomes.includes(edge.outcome!))
                    return {
                        value: operation.key,
                        label: operation.name,
                        disabledReason: missingOutcome
                            ? `Remove the ${getOutcomeLabel(missingOutcome.outcome!)} path first`
                            : undefined,
                    }
                }),
        ],
    }),
    listeners(({ actions, values, props }) => ({
        setOperation: ({ operation }) => {
            const action = values.action
            const option = values.operationOptions.find((candidate) => candidate.value === operation)
            if (!action || !option || option.disabledReason || action.config.operation === operation) {
                return
            }
            actions.setWorkflowAction(props.actionId, {
                ...action,
                config: { ...action.config, operation, inputs: {} },
            })
        },
        addOutcomePath: ({ outcome }) => {
            const exitAction = values.workflow.actions.find((action) => action.type === 'exit')
            if (!exitAction || values.outcomePaths.find((path) => path.outcome === outcome)?.hasPath !== false) {
                return
            }
            actions.setWorkflowActionEdges(props.actionId, [
                { from: props.actionId, to: exitAction.id, type: 'branch', outcome },
                ...values.actionEdges,
            ])
        },
        removeOutcomePath: ({ outcome }) => {
            const path = values.outcomePaths.find((candidate) => candidate.outcome === outcome)
            if (!path?.hasPath || path.removeDisabledReason) {
                return
            }
            const edge = values.outcomeEdges.find((candidate) => candidate.outcome === outcome)
            actions.setWorkflowActionEdges(
                props.actionId,
                values.actionEdges.filter((candidate) => candidate !== edge)
            )
        },
    })),
])
