// PROTOTYPE helper: renders the Mermaid blocks in brief.src.html to inline SVG and writes index.html,
// so the brief needs no JavaScript in the viewer. Run: node render.mjs (uses the repo's playwright).
import { readFileSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

import { chromium } from '../../../../../../node_modules/playwright/index.mjs'

const here = dirname(fileURLToPath(import.meta.url))
const source = join(here, 'brief.src.html')
const browser = await chromium.launch()
const page = await browser.newPage({ viewport: { width: 1280, height: 900 } })
await page.goto('file://' + source)
await page.waitForFunction(() => [...document.querySelectorAll('pre.mermaid')].every((el) => el.querySelector('svg')))
const svgs = await page.$$eval('pre.mermaid', (els) => els.map((el) => el.innerHTML))
await browser.close()

let html = readFileSync(source, 'utf8')
let index = 0
html = html.replace(/<pre class="mermaid">[\s\S]*?<\/pre>/g, () => `<div class="mermaid">${svgs[index++]}</div>`)
html = html.replace(/<script type="module">[\s\S]*?<\/script>\n/, '')
html = html.replace(
    '<title>',
    '<!-- Generated by render.mjs from brief.src.html. Edit the source, then re-run. -->\n<title>'
)
writeFileSync(join(here, 'index.html'), html)
