import { MakeLogicType, actions, afterMount, connect, kea, key, listeners, path, props, reducers, selectors } from 'kea'
import { loaders } from 'kea-loaders'
import posthog from 'posthog-js'

import api from 'lib/api'

import { sidePanelStateLogic } from '~/layout/navigation-3000/sidepanel/sidePanelStateLogic'
import {
    FeatureFlagHealthQuery,
    FeatureFlagHealthQueryResponse,
    FeatureFlagHealthResult,
    FeatureFlagHealthVerdict,
    NodeKind,
} from '~/queries/schema/schema-general'
import { SidePanelTab } from '~/types'

import {
    featureFlagHealthErrorTrackingUrl,
    featureFlagHealthInvestigationPrompt,
} from './featureFlagHealthInvestigation'

export type FeatureFlagHealthPeriod = '24h' | '7d'

export interface FeatureFlagHealthLogicProps {
    flagKey: string
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface featureFlagHealthLogicValues {
    canInvestigate: boolean
    errorTrackingUrl: string
    health: FeatureFlagHealthResult | null
    healthResponse: FeatureFlagHealthQueryResponse | null
    healthResponseLoading: boolean
    investigationPrompt: string | null
    loadFailed: boolean
    period: FeatureFlagHealthPeriod
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface featureFlagHealthLogicActions {
    openSidePanel: (
        tab: SidePanelTab,
        options?: string
    ) => {
        tab: SidePanelTab
        options: string | undefined
    } // sidePanelStateLogic
    investigateWithAI: () => {
        value: true
    }
    loadHealthResponse: (_: void) => void
    loadHealthResponseFailure: (
        error: string,
        errorObject?: any
    ) => {
        error: string
        errorObject?: any
    }
    loadHealthResponseSuccess: (
        healthResponse: FeatureFlagHealthQueryResponse,
        payload?: void
    ) => {
        healthResponse: FeatureFlagHealthQueryResponse
        payload?: void
    }
    setPeriod: (period: FeatureFlagHealthPeriod) => {
        period: FeatureFlagHealthPeriod
    }
    viewErrors: () => {
        value: true
    }
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface featureFlagHealthLogicMeta {
    key: string
    __keaTypeGenInternalSelectorTypes: {
        canInvestigate: (health: FeatureFlagHealthResult | null) => boolean
        errorTrackingUrl: (period: FeatureFlagHealthPeriod) => string
        health: (healthResponse: FeatureFlagHealthQueryResponse | null) => FeatureFlagHealthResult | null
        investigationPrompt: (health: FeatureFlagHealthResult | null, period: FeatureFlagHealthPeriod) => string | null
    }
}

export type featureFlagHealthLogicType = MakeLogicType<
    featureFlagHealthLogicValues,
    featureFlagHealthLogicActions,
    FeatureFlagHealthLogicProps,
    featureFlagHealthLogicMeta
>

export const featureFlagHealthLogic = kea<featureFlagHealthLogicType>([
    props({} as FeatureFlagHealthLogicProps),
    key((props) => props.flagKey),
    path((key) => ['products', 'feature_flags', 'frontend', 'health', 'featureFlagHealthLogic', key]),
    connect(() => ({
        actions: [sidePanelStateLogic, ['openSidePanel']],
    })),
    actions({
        setPeriod: (period: FeatureFlagHealthPeriod) => ({ period }),
        viewErrors: true,
        investigateWithAI: true,
    }),
    loaders(({ props, values }) => ({
        healthResponse: [
            null as FeatureFlagHealthQueryResponse | null,
            {
                loadHealthResponse: async (_: void, breakpoint): Promise<FeatureFlagHealthQueryResponse> => {
                    const query: FeatureFlagHealthQuery = {
                        kind: NodeKind.FeatureFlagHealthQuery,
                        flagKey: props.flagKey,
                        dateRange: { date_from: `-${values.period}` },
                    }
                    try {
                        const response = await api.query(query)
                        breakpoint()
                        return response
                    } catch (error) {
                        breakpoint()
                        throw error
                    }
                },
            },
        ],
    })),
    reducers({
        period: [
            '24h' as FeatureFlagHealthPeriod,
            {
                setPeriod: (_, { period }) => period,
            },
        ],
        loadFailed: [
            false,
            {
                loadHealthResponse: () => false,
                loadHealthResponseSuccess: () => false,
                loadHealthResponseFailure: () => true,
            },
        ],
    }),
    selectors(({ props }) => ({
        health: [
            (s) => [s.healthResponse],
            (healthResponse: FeatureFlagHealthQueryResponse | null): FeatureFlagHealthResult | null =>
                healthResponse?.results[0] ?? null,
        ],
        canInvestigate: [
            (s) => [s.health],
            (health: FeatureFlagHealthResult | null): boolean =>
                !!health && health.verdict !== FeatureFlagHealthVerdict.TelemetryFailure,
        ],
        errorTrackingUrl: [
            (s) => [s.period],
            (period: FeatureFlagHealthPeriod): string => featureFlagHealthErrorTrackingUrl(props.flagKey, period),
        ],
        investigationPrompt: [
            (s) => [s.health, s.period],
            (health: FeatureFlagHealthResult | null, period: FeatureFlagHealthPeriod): string | null =>
                health ? featureFlagHealthInvestigationPrompt(props.flagKey, period, health) : null,
        ],
    })),
    listeners(({ actions, values }) => ({
        setPeriod: ({ period }) => {
            // pinned: analytics event name, renaming breaks dashboards
            posthog.capture('feature flag health period changed', { period })
            actions.loadHealthResponse()
        },
        viewErrors: () => {
            // pinned: analytics event name, renaming breaks dashboards
            posthog.capture('feature flag health errors viewed', {
                period: values.period,
                verdict: values.health?.verdict,
            })
        },
        investigateWithAI: () => {
            if (!values.investigationPrompt) {
                return
            }
            // pinned: analytics event name, renaming breaks dashboards
            posthog.capture('feature flag health ai investigation started', {
                period: values.period,
                verdict: values.health?.verdict,
            })
            actions.openSidePanel(SidePanelTab.Max, `!${values.investigationPrompt}`)
        },
    })),
    afterMount(({ actions, values }) => {
        // pinned: analytics event name, renaming breaks dashboards
        posthog.capture('feature flag health viewed', { period: values.period })
        actions.loadHealthResponse()
    }),
])
